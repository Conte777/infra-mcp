// render is what the model actually receives; a test that reads the blocks
// instead would miss the budget and the escaping.
func render(t *testing.T, cfg Config, blocks []block.Block) string {
	t.Helper()
	return block.Markdown(blocks, cfg.Output.Budget())
}

func table(t *testing.T, blocks []block.Block) block.Table {
	t.Helper()
	if len(blocks) != 1 {
		t.Fatalf("%d blocks, want one table", len(blocks))
	}
	tbl, ok := blocks[0].(block.Table)
	if !ok {
		t.Fatalf("block is %T, want a table", blocks[0])
	}
	return tbl
}

func column(t *testing.T, tbl block.Table, name string) []string {
	t.Helper()
	at := -1
	for i, c := range tbl.Columns {
		if c == name {
			at = i
		}
	}
	if at < 0 {
		t.Fatalf("no column %q in %v", name, tbl.Columns)
	}
	var out []string
	for _, row := range tbl.Rows {
		s, _ := row[at].(string)
		out = append(out, s)
	}
	return out
}

// A database the tools refuse to reach must not be listed either, or the model
// spends its next call finding that out.
func TestListDatabasesShowsWhatTheToolsCanReach(t *testing.T) {
	s, cfg := testSource(t, nil)

	list := func(t *testing.T, cfg Config) []string {
		t.Helper()
		blocks, err := runRead(t, s, cfg, ConnectionArgs{Address: testCluster}, listDatabases)
		if err != nil {
			t.Fatalf("list: %v", err)
		}
		return column(t, table(t, blocks), "database")
	}

	if got := list(t, cfg); len(got) < 2 {
		t.Fatalf("databases = %v, want the whole cluster with no include", got)
	}

	only := cfg
	only.Databases.Include = []string{cfg.Databases.Default}
	if got := list(t, only); len(got) != 1 || got[0] != cfg.Databases.Default {
		t.Errorf("databases = %v, want only %q", got, cfg.Databases.Default)
	}

	hidden := cfg
	hidden.Databases.Exclude = []string{otherDatabase}
	for _, db := range list(t, hidden) {
		if db == otherDatabase {
			t.Errorf("%q is listed although databases.exclude hides it", db)
		}
	}

	// The database the query itself runs in is an entry point, not a licence:
	// an include naming one database has to yield one.
	entry := cfg
	entry.Databases.Include = []string{otherDatabase}
	got := list(t, entry)
	if len(got) != 1 || got[0] != otherDatabase {
		t.Errorf("databases = %v, want only %q — the entry point listed itself", got, otherDatabase)
	}
}

func TestListTables(t *testing.T) {
	s, cfg := testSource(t, nil)
	exec(t, cfg, cfg.Databases.Default, `
		CREATE TABLE orders (id int PRIMARY KEY);
		CREATE TABLE order_items (id int, order_id int REFERENCES orders(id));
		CREATE TABLE customers (id int);
		CREATE VIEW recent_orders AS SELECT id FROM orders;
		CREATE TABLE events (id int, at date) PARTITION BY RANGE (at);
		CREATE TABLE events_2026 PARTITION OF events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
		COMMENT ON TABLE orders IS 'what people bought'`)

	blocks, err := runRead(t, s, cfg, listTablesArgs{Args: callArgs(cfg)}, listTables)
	if err != nil {
		t.Fatalf("list: %v", err)
	}
	tbl := table(t, blocks)

	names := column(t, tbl, "table")
	for _, want := range []string{"public.orders", "public.recent_orders", "public.events"} {
		if !contains(names, want) {
			t.Errorf("%q missing from %v", want, names)
		}
	}
	// A partitioned table with a hundred children would otherwise bury the
	// tables somebody asked about.
	if contains(names, "public.events_2026") {
		t.Errorf("a partition is listed as a table: %v", names)
	}

	kinds := map[string]string{}
	for i, name := range names {
		kinds[name] = column(t, tbl, "kind")[i]
	}
	if kinds["public.recent_orders"] != "view" || kinds["public.events"] != "partitioned" {
		t.Errorf("kinds = %v", kinds)
	}
	if !strings.Contains(render(t, cfg, blocks), "what people bought") {
		t.Error("the table comment did not reach the answer")
	}

	blocks, err = runRead(t, s, cfg, listTablesArgs{Args: callArgs(cfg), Pattern: "order%"}, listTables)
	if err != nil {
		t.Fatalf("list with a pattern: %v", err)
	}
	narrowed := column(t, table(t, blocks), "table")
	if len(narrowed) != 2 || !contains(narrowed, "public.orders") || !contains(narrowed, "public.order_items") {
		t.Errorf("pattern order%% matched %v", narrowed)
	}
}

const describeSchema = `
	CREATE SCHEMA app;
	CREATE TABLE app.orgs (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		name text NOT NULL
	);
	CREATE TABLE app.users (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		org_id bigint NOT NULL REFERENCES app.orgs(id),
		email text NOT NULL UNIQUE,
		age int CHECK (age >= 0),
		created_at timestamptz NOT NULL DEFAULT now()
	);
	CREATE INDEX users_created_idx ON app.users (created_at);
	COMMENT ON TABLE app.users IS 'people';
	COMMENT ON COLUMN app.users.email IS E'login\nname';
	CREATE VIEW app.adults AS SELECT id FROM app.users WHERE age >= 18`

func TestDescribeTable(t *testing.T) {
	s, cfg := testSource(t, nil)
	exec(t, cfg, cfg.Databases.Default, describeSchema)

	blocks, err := runRead(t, s, cfg, describeArgs{Args: callArgs(cfg), Tables: []string{"app.users", "app.orgs"}}, describeTable)
	if err != nil {
		t.Fatalf("describe: %v", err)
	}
	if len(blocks) != 2 {
		t.Fatalf("%d blocks for two tables, want one each", len(blocks))
	}
	code, ok := blocks[0].(block.Code)
	if !ok || code.Lang != "sql" {
		t.Fatalf("block is %T (%v), want DDL", blocks[0], blocks[0])
	}

	users := code.Text
	for _, want := range []string{
		"-- app.users: table",
		"-- people",
		"CREATE TABLE app.users (",
		"id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL",
		"created_at timestamp with time zone DEFAULT now() NOT NULL",
		"CONSTRAINT users_pkey PRIMARY KEY (id)",
		"FOREIGN KEY (org_id) REFERENCES app.orgs(id)",
		"CHECK ((age >= 0))",
		"CREATE INDEX users_created_idx",
	} {
		if !strings.Contains(users, want) {
			t.Errorf("%q missing from the DDL:\n%s", want, users)
		}
	}
	// A newline in a comment would turn the rest of it into DDL.
	if !strings.Contains(users, "-- login name") {
		t.Errorf("the column comment is missing or broke the line:\n%s", users)
	}
	if strings.Contains(users, "CREATE INDEX users_pkey") || strings.Contains(users, "users_email_key ON") {
		t.Errorf("an index backing a constraint is printed twice:\n%s", users)
	}

	orgs, _ := blocks[1].(block.Code)
	// Which tables break if a row here goes is not in this table's own DDL.
	if !strings.Contains(orgs.Text, "-- referenced by app.users: FOREIGN KEY (org_id)") {
		t.Errorf("the inbound foreign key is missing:\n%s", orgs.Text)
	}
}

